#!/usr/bin/env python3
"""Export a bounded, auditable Research Engine packet for the ChatGPT editor.

Input: six verified workbenches generated by our official-source parsers.
Output: RESEARCH DATA ONLY, never an article, never an Android feed.
No model, credentials, publication, or API usage.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re

from scripts.pulse_editorial_ai import _read_input
from scripts.pulse_research_acceptance import verify_six
from scripts.pulse_research_engine import research_report

SCHEMA = "pulse-research-to-chatgpt-v1"
SHA = re.compile(r"[0-9a-f]{64}\Z")
DOMAINS = ("tourism", "labor", "prices", "demography", "education", "environment")
COLLECTIONS = (
    ("research_candidates", "tourism"),
    ("labor_signals", "labor"),
    ("price_signals", "prices"),
    ("demography_signals", "demography"),
    ("historical_signals", "education"),
    ("territorial_signals", "environment"),
)
ALLOWED_FIELDS = {
    "indicator", "indicator_code", "population", "population_group", "population_scope",
    "segment", "period", "periods", "unit", "units", "value", "observed_total",
    "reported_yoy_change_pct", "change_pct", "values", "first_value", "last_value",
    "absolute_change", "absolute_change_unit", "low", "high", "gap", "gap_unit",
    "price_index_code", "index_level", "indicator_evidence", "evidence", "territory",
    "name", "observations", "rounded_at_thousands", "comparison_basis",
    "sex", "age", "group", "from_value", "to_value", "ratio", "observed_index", "reported_monthly_change_pct",
    "reported_monthly_change_thousands", "reference_period", "reference_comparison",
    "source_count_thousands", "reported_yoy_change_thousands", "source_table_unit",
    "unit_multiplier", "age_scope", "sex_scope", "rounded_at_thousands", "provisional",
    "basket", "code", "territory_level", "denominator", "comparison",
}


def compact(value, depth=0):
    """Only selected source-verified fields; exclude unverified narrative leads."""
    if depth > 5:
        return None
    if isinstance(value, dict):
        return {k: compact(v, depth + 1) for k, v in value.items()
                if k in ALLOWED_FIELDS and compact(v, depth + 1) is not None}
    if isinstance(value, list):
        return [compact(v, depth + 1) for v in value[:30]]
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value if not isinstance(value, str) else value[:260]
    return None


def make_packet(paths: list[Path]) -> dict:
    accepted = verify_six(paths)  # fail closed on any official fact mismatch
    articles = []
    for path in paths:
        articles.extend(_read_input(path))
    report = research_report(articles, limit=10)
    if report["source_document_count"] != 6 or len(report["research_stories"]) != 16:
        raise ValueError("Unexpected validated research coverage")
    allowed_urls = {
        x["source_url"] for x in report["publication_coverage"]
        if x["full_text_layer_attached"] and x["complete_text_layer"]
    }
    if len(allowed_urls) != 6:
        raise ValueError("Six complete independently attached PDF sources required")
    stories = []
    for collection, domain in COLLECTIONS:
        for number, signal in enumerate(report[collection], 1):
            source = signal.get("source_url")
            if source not in allowed_urls:
                raise ValueError("Unverified source in research evidence")
            evidence = signal.get("evidence") or signal.get("indicator_evidence") or []
            if not isinstance(evidence, list):
                evidence = []
            raw_hash = signal.get("source_sha256")
            if not raw_hash:
                raw_hash = next((x.get("source_sha256") for x in evidence
                                 if isinstance(x, dict) and x.get("source_sha256")), None)
            if not isinstance(raw_hash, str) or not SHA.fullmatch(raw_hash):
                # A story without a verifiable document fingerprint cannot be a fact packet.
                raise ValueError(f"Missing PDF SHA-256: {domain}/{number}")
            source_locations = (signal.get("source_locations") or
                                [x.get("source_location") for x in evidence
                                 if isinstance(x, dict) and x.get("source_location")] or
                                ([signal["source_location"]] if signal.get("source_location") else []))
            if not source_locations and collection == "territorial_signals":
                source_locations = [x.get("source_location") for x in
                                    (signal.get("low") or {}, signal.get("high") or {})
                                    if isinstance(x, dict) and x.get("source_location")]
            if not source_locations:
                raise ValueError(f"Missing source table locator: {domain}/{number}")
            structural = compact(signal)
            story_id = f"{domain.upper()}-{number:02d}-{raw_hash[:10]}"
            fact_id = f"E-{story_id}-01"
            stories.append({
                "story_id": story_id,
                "domain": domain,
                "source_url": source,
                "source_sha256": raw_hash,
                "source_locations": list(dict.fromkeys(str(s)[:200] for s in source_locations)),
                "facts": [{
                    "evidence_id": fact_id,
                    "source_url": source,
                    "source_sha256": raw_hash,
                    "source_locations": source_locations,
                    "verified_structured_data": structural,
                }],
                "status": "research_verified_not_an_article",
                "human_fact_review_required": True,
            })
    if len(stories) != 16:
        raise ValueError(f"Expected 16 evidenced stories, not {len(stories)}")
    return {
        "schema_version": SCHEMA,
        "purpose": "source_locked_evidence_for_chatgpt_not_for_app",
        "packet_id": "SIX-OFFICIAL-PDFS-20261011",
        "validated_official_pdf_count": accepted["source_documents"],
        "validated_observation_count": accepted["verified_numeric_observations"],
        "validated_source_pages": accepted["pdf_pages_total"],
        "stories": stories,
        "publication_allowed": False,
        "human_review_required": True,
        "limitations": [
            "Six explicitly supported and historically dated source PDFs only.",
            "A story's verified structured data is not permission to infer causality or add new numbers.",
            "This is not a live universal collector of all ISTAT releases.",
        ]
    }


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("workbenches", nargs=6, type=Path)
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    if args.output.resolve() in {x.resolve() for x in args.workbenches}:
        p.error("Do not overwrite workbenches")
    packet = make_packet(args.workbenches)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(packet, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({
        "packet": packet["packet_id"], "stories": len(packet["stories"]),
        "pdfs": packet["validated_official_pdf_count"],
        "verified_observations": packet["validated_observation_count"],
        "sha256": hashlib.sha256(args.output.read_bytes()).hexdigest(),
        "auto_published": False,
    }))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
